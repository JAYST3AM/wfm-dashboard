def main():
    ap = argparse.ArgumentParser(description='Trading Session workflow acceptance gate')
    ap.add_argument('--keep', action='store_true', help='keep the throwaway data dir + raw JSON')
    args = ap.parse_args()

    now_local = datetime.now().astimezone().strftime('%Y-%m-%d %H:%M:%S %z')
    launcher = {'facts': [], 'real_data_before': real_snapshot(), 'real_data_after': None}
    launcher.update(git_facts())
    tmp = tempfile.mkdtemp(prefix='wfm-workflow-gate-')
    data = os.path.join(tmp, 'data')
    os.makedirs(data)
    raw = {}
    boot_lines = []
    node_out = ''
    proc = None
    port = free_port()
    base = 'http://127.0.0.1:%d' % port
    try:
        print('[1/5] seeding the throwaway data dir: %s' % data)
        seed_data(data)
        # data/config.json for the gate server: the auto-refresh knob controls the app's own poll
        # cadence (what the reconcile check rides). 0 keeps the server-side pipeline off; the page
        # treats 0 as "no value" and polls every 30s, which is what this run waits for.
        jwrite(os.path.join(data, 'config.json'),
               {'port': port, 'host': '127.0.0.1', 'auto_refresh_seconds': 0, 'gamenews_cache_seconds': 86400})
        boot = os.path.join(tmp, '_gate_boot.py')
        with open(boot, 'w', encoding='utf-8') as fh:
            fh.write(boot_source())

        print('[2/5] booting the dashboard on %s (WFM_DATA=%s)' % (base, data))
        env = dict(os.environ)
        env.update({'WFM_ROOT': REPO, 'WFM_DATA': data, 'WFM_PORT': str(port), 'WFM_HOST': '127.0.0.1',
                    'WFM_CONFIG': os.path.join(data, 'config.json'), 'WFM_SYNC_SLICE': '5',
                    'PYTHONIOENCODING': 'utf-8'})
        server_log = os.path.join(tmp, 'gate-server.log')
        sink = open(server_log, 'wb')
        proc = subprocess.Popen([sys.executable, boot], cwd=REPO, env=env,
                                stdout=sink, stderr=subprocess.STDOUT)

        deadline = time.time() + 90
        code, body = 0, None
        while time.time() < deadline:
            if proc.poll() is not None:
                break
            code, body = http_json(base + '/api/session', timeout=3)
            if code == 200 and isinstance(body, dict) and body.get('ok') is True:
                break
            time.sleep(0.4)
        try:
            sink.flush()
            sink.close()
        except Exception:
            pass
        try:
            with open(server_log, encoding='utf-8', errors='replace') as fh:
                out = fh.read()
        except OSError:
            out = ''
        boot_lines = [ln.strip() for ln in out.splitlines() if ln.strip()]
        if code != 200:
            raise RuntimeError('the gate server never answered on %s. log tail:\n%s' % (base, out[-1500:]))

        got_data = next((l.split('=', 1)[1] for l in boot_lines if l.startswith('GATE_DATA=')), '')
        got_whisper = next((l.split('=', 1)[1] for l in boot_lines if l.startswith('GATE_WHISPER=')), '')
        launcher['facts'].append(['server booted against the throwaway data dir',
                                  'yes' if os.path.normcase(os.path.abspath(got_data)) ==
                                  os.path.normcase(os.path.abspath(data)) else
                                  'NO — GATE_DATA=%s' % got_data])
        launcher['facts'].append(['whisper transport', 'stubbed (GATE_WHISPER=%s)' % (got_whisper or '?')])
        launcher['facts'].append(['the queue the server BUILT from the throwaway payloads',
                                  ', '.join(str(r.get('slug')) for r in (body or {}).get('suggested') or [])
                                  or '(none - the payloads were not read)'])

        print('[3/5] driving the browser (Whisper -> CONTACTED -> check -> Confirm) ...')
        raw_path = os.path.join(tmp, 'workflow-raw.json')
        nenv = dict(env)
        nenv.update({'WFM_BASE': base, 'WFM_DATA': data, 'WFM_RAW': raw_path,
                     'WFM_PROFILE': os.path.join(tmp, 'chrome-profile'), 'WFM_CHROME': CHROME,
                     'WFM_SLUG': SEED['slug']})
        spawned = time.time()
        p = subprocess.run(['node', DRIVER], cwd=REPO, env=nenv, capture_output=True, text=True,
                           timeout=600)
        node_out = (p.stdout or '') + (('\n' + p.stderr) if p.stderr else '')
        print('  node rc=%s in %ss' % (p.returncode, round(time.time() - spawned, 1)))
        for ln in (p.stdout or '').strip().splitlines():
            print('  ' + ln)

        print('[4/5] merging the result into %s ...' % os.path.basename(REPORT))
        raw = json.load(open(raw_path, encoding='utf-8')) if os.path.isfile(raw_path) else {}
        if not raw:
            raw = {'verdict': {'pass': False, 'crashed': 'the driver wrote no raw result:\n' + node_out[-1500:]},
                   'checks': [], 'meta': {}, 'evidence': {}}
        launcher['real_data_after'] = real_snapshot()
        # proof the session the driver drove lives in the throwaway dir, read from the driver's
        # own evidence rather than asserted here
        ev = raw.get('evidence', {})
        sess = (ev.get('start') or {}).get('session') or {}
        pend = ((ev.get('whisper') or {}).get('pending') or [{}])[0]
        launcher['facts'].append(['the session the driver started names the fixture account',
                                  '`%s` (plat_start=%s)' % (sess.get('account'), sess.get('plat_start'))
                                  if sess.get('account') == SEED['account'] else
                                  'NO — account=%r' % sess.get('account')])
        launcher['facts'].append(['the CONTACTED snapshot the server took',
                                  'id=%s state=%s copies=%s plat=%s asked=%sp x%s'
                                  % (pend.get('id'), pend.get('state'), pend.get('inv_before'),
                                     pend.get('plat_before'), pend.get('expected_plat'), pend.get('qty'))])
        launcher['facts'].append(['the trade the Confirm click wrote',
                                  json.dumps((((ev.get('confirm') or ev.get('confirm_probe') or {})
                                               .get('trade_log') or [{}])[0]))[:220]])
        md = build_report(raw, launcher, boot_lines, now_local, args.keep, tmp)
        with open(REPORT, 'w', encoding='utf-8') as fh:
            fh.write(md)
        print('  %s bytes -> %s' % (len(md), REPORT))
    finally:
        if proc is not None and proc.poll() is None:
            proc.terminate()
            try:
                proc.wait(timeout=10)
            except Exception:
                proc.kill()
        if not args.keep:
            shutil.rmtree(tmp, ignore_errors=True)
        else:
            print('kept: %s' % tmp)

    checks = raw.get('checks', [])
    failed = [c for c in checks if not c.get('ok')]
    ok = bool(raw.get('verdict', {}).get('pass')) and not failed
    print('[5/5] verdict')
    for c in checks:
        print('  %s [%s] %s' % ('ok  ' if c.get('ok') else 'FAIL', c.get('step'), c.get('title')))
        if not c.get('ok'):
            print('       expected: %s' % c.get('expected'))
            print('       observed: %s' % c.get('observed'))
    if raw.get('verdict', {}).get('crashed'):
        print('  CRASH: %s' % str(raw['verdict']['crashed'])[:400])
    print('WORKFLOW %s - %d of %d checks' % ('PASS' if ok else 'FAIL',
                                             len(checks) - len(failed), len(checks)))
    sys.exit(0 if ok else 1)


