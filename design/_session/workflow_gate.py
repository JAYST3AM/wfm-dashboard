def git_facts():
    """The revision the result belongs to. A harness that reports on a working tree has to say
    which working tree."""
    def run(args):
        try:
            p = subprocess.run(['git'] + args, cwd=REPO, capture_output=True, text=True, timeout=30)
            return (p.stdout or '').strip()
        except Exception:
            return ''
    dirty = run(['status', '--porcelain']).splitlines()
    return {'rev': run(['rev-parse', '--short', 'HEAD']) or '?',
            'dirty': '; '.join(x.strip() for x in dirty)[:300],
            'files_changed': len(dirty)}


def real_snapshot():
    """Informational only: the repo's real data/ files this gate could plausibly disturb.
    The developer's own supervised app may write them at any time, so this is reported as a fact,
    never asserted."""
    out = {}
    for name in ('trade_session.json', 'trade_log.json', 'whisper_log.json', 'report.json',
                 'plat_history.json', 'trader_limits.json', 'sync_log.json'):
        p = os.path.join(REPO, 'data', name)
        try:
            st = os.stat(p)
            out[name] = {'exists': True, 'bytes': st.st_size, 'mtime': int(st.st_mtime)}
        except OSError:
            out[name] = {'exists': False}
    return out


def free_port():
    s = socket.socket()
    s.bind(('127.0.0.1', 0))
    port = s.getsockname()[1]
    s.close()
    return port


def http_json(url, timeout=8):
    try:
        with urllib.request.urlopen(url, timeout=timeout) as r:
            return r.status, json.loads(r.read().decode('utf-8'))
    except urllib.error.HTTPError as e:
        try:
            return e.code, json.loads(e.read().decode('utf-8'))
        except Exception:
            return e.code, None
    except Exception as e:
        return 0, {'error': str(e)[:200]}


def wait_ready(base, proc, log_path, timeout=90):
    """Poll GET /api/session until the gate server answers, or say why it never did."""
    deadline = time.time() + timeout
    while time.time() < deadline:
        if proc.poll() is not None:
            return 'the gate server exited (rc=%s)' % proc.returncode
        code, body = http_json(base + '/api/session', timeout=3)
        if code == 200 and isinstance(body, dict) and body.get('ok') is True:
            return None
        time.sleep(0.4)
    tail = ''
    try:
        tail = open(log_path, encoding='utf-8', errors='replace').read()[-1500:]
    except OSError:
        pass
    return 'the gate server never answered on %s within %ss. log tail:\n%s' % (base, timeout, tail)


def md_table(head, rows):
    out = ['| ' + ' | '.join(str(h) for h in head) + ' |',
           '|' + '|'.join(['---'] * len(head)) + '|']
    for r in rows:
        out.append('| ' + ' | '.join('' if c is None else str(c) for c in r) + ' |')
    return '\n'.join(out)


def esc(s, limit=180):
    return str('' if s is None else s).replace('|', '\\|').replace('\n', ' ')[:limit]


