#!/usr/bin/env python
"""design/_session/workflow_gate.py - the Trading Session WORKFLOW acceptance gate, one command.

    python design/_session/workflow_gate.py            # run it, write workflow-report.md
    python design/_session/workflow_gate.py --keep     # same, but keep the throwaway dir

What it does, in order:
  1. makes a THROWAWAY data dir and seeds it with the payloads the session queue is built from
     (trader_plan.json, report.json, run_queue.json, trader_limits.json, plat_history.json)
  2. boots a real dashboard server on a free port with WFM_DATA pointing at that dir
  3. runs design/_session/workflow_gate.js (puppeteer-core), which drives the REAL UI through
     Whisper -> CONTACTED -> the reconcile check -> Confirm, reading every claim back from the
     DOM, from the app's own HTTP answers and from the store files on disk
  4. tears the server down, merges the driver's result into design/_session/workflow-report.md,
     prints the PASS/FAIL verdict with the observed evidence, and exits 0/1

WHAT IT DOES NOT DO, ON PURPOSE (all of it repeated in the report)
  - it never touches the repo's real data/: the server is booted with WFM_ROOT=<repo> (so the real
    static/ and scripts/ serve the page) and WFM_DATA=<throwaway>, and the boot script prints
    GATE_DATA so the run can prove which dir the server actually used.
  - it never sends a real whisper to a real player. scripts/whisper.py types the line into a
    running Warframe window; in a gate run the boot script replaces ONLY whisper.send() with a
    stub that reports the same success a delivered whisper reports. message()/line()/copy() and
    every line of server.py after them are the real code.
  - it never runs the local pipeline: the confirmation's background sync kick is stubbed out
    (exactly what tests/test_session_api.py does) because scripts/refresh.py + invdiff.py do not
    read WFM_DATA and would rewrite the developer's real data/.
"""
