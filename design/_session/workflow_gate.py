def boot_source():
    """The gate's server bootstrap, with this checkout's repo path baked in (never hardcoded)."""
    return BOOT_TEMPLATE.replace('@@REPO@@', repr(REPO.replace('\\', '/')))


def jwrite(path, obj):
    with open(path, 'w', encoding='utf-8') as fh:
        json.dump(obj, fh, indent=1)


