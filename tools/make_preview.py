# selftest                                                                                  #
# --------------------------------------------------------------------------------------- #
def selftest():
    ok = True

    def chk(name, cond):
        nonlocal ok
        ok = ok and bool(cond)
        say('  %s %s' % ('ok  ' if cond else 'FAIL', name))

    # png_size reads a real PNG built with stdlib only
    tmp = os.path.join(FRAMES, '_selftest.png')
    os.makedirs(FRAMES, exist_ok=True)
    with open(tmp, 'wb') as f:
        f.write(make_tiny_png())
    chk('png_size() reads a stdlib-built 1x1 PNG', png_size(tmp) == (1, 1))
    chk('png_size() rejects a non-PNG', png_size(os.path.abspath(__file__)) is None)

    # driver template renders to valid JSON config
    cfg = dict(url='http://127.0.0.1:8787', cadence=700, w=1440, h=900, theme=14, scrub=['A', 'B'],
               frames=FRAMES, assets=ASSETS, puppeteer='x', chrome='y', posters=True,
               poster_w=1440, poster_h=1000,
               holds=dict(home=1, trader=1, guardrails=1, theme=1, market=1, market_scroll=1,
                          collection=1, cards=1))
    js = DRIVER_CJS.replace('__CFG_JSON__', json.dumps(cfg))
    chk('driver template substitutes the config token', '__CFG_JSON__' not in js and '"cadence": 700' in js)
    chk('driver template is plain CommonJS (require, no import)', js.startswith("'use strict';") and 'require(CFG.puppeteer)' in js)

    # tier ladder only ever gets cheaper
    ts = tiers(960, 8)
    chk('tiers() start at the requested width/fps', ts[0] == (960, 8, 256))
    chk('tiers() never upscale past the request', all(t[0] <= 960 and t[1] <= 8 for t in ts))
    chk('tiers() are unique and end cheaper', len(ts) == len(set(ts)) and ts[-1][0] < 960 and ts[-1][1] <= 8)

    # scrub handling
    chk("resolve_scrub('') turns redaction off", resolve_scrub('') == [])
    chk('resolve_scrub parses an explicit list', resolve_scrub('A B,C') == ['A B', 'C'])
    chk('make_preview.py never hard-codes an account handle',
        ('Royal' + 'Spartan') not in open(os.path.abspath(__file__), encoding='utf-8').read())

    try:
        os.remove(tmp)
    except OSError:
        pass
    say('selftest: ' + ('PASS' if ok else 'FAIL'))
    return 0 if ok else 1


