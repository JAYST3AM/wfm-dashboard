def assemble_gif_ffmpeg(ffmpeg, frame_paths, out_path, max_mb, first_w, fps, width):
    pattern = os.path.join(FRAMES, 'frame_%03d.png')
    frames = len(frame_paths)
    scale_w = width
    last = None
    for (w, f, colors) in tiers(width, fps):
        gif_tmp = os.path.join(FRAMES, 'preview_build.gif')
        pal_tmp = os.path.join(FRAMES, 'palette_build.png')
        vf1 = 'scale=%d:-2:flags=lanczos,palettegen=max_colors=%d:stats_mode=diff' % (w, colors)
        rc1, _, err1 = run([ffmpeg, '-y', '-hide_banner', '-loglevel', 'error',
                            '-framerate', str(f), '-i', pattern, '-vf', vf1, pal_tmp])
        if rc1 != 0:
            last = 'palettegen failed: ' + (err1 or '')[-300:]
            continue
        lavfi = 'scale=%d:-2:flags=lanczos[x];[x][1:v]paletteuse=dither=bayer:bayer_scale=3:diff_mode=rectangle' % w
        rc2, _, err2 = run([ffmpeg, '-y', '-hide_banner', '-loglevel', 'error',
                            '-framerate', str(f), '-i', pattern, '-i', pal_tmp,
                            '-lavfi', lavfi, '-loop', '0', gif_tmp])
        if rc2 != 0:
            last = 'paletteuse failed: ' + (err2 or '')[-300:]
            continue
        size = os.path.getsize(gif_tmp)
        if size <= max_mb * 1024 * 1024:
            os.makedirs(os.path.dirname(out_path), exist_ok=True)
            how = replace_with_retry(gif_tmp, out_path)
            return dict(tool='ffmpeg', path=out_path, size=size, width=w, fps=f,
                        colors=colors, frames=frames, duration=frames / float(f),
                        publish=how,
                        note='frame #1 was %dx%d, scaled to %dpx wide' % (first_w[0], first_w[1], w))
        last = '%d px @ %d fps / %d colours = %.2f MB (over budget)' % (w, f, colors, size / 1048576.0)
        say('  ... %s, stepping down' % last)
        scale_w = w
    return dict(tool='ffmpeg', path=None, error=last or 'no tier produced a GIF', width=scale_w, fps=fps, frames=frames)


def assemble_pillow(frame_paths, out_path, width, fps, max_mb):
    from PIL import Image
    frames = []
    for p in frame_paths:
        im = Image.open(p).convert('RGB')
        if im.width != width:
            im = im.resize((width, max(2, int(round(im.height * width / float(im.width))))), Image.LANCZOS)
        frames.append(im)
    duration = int(round(1000.0 / fps))
    written = {}

    def save(img_list, target, **kwargs):
        tmp = target + '.tmp' + os.path.splitext(target)[1]
        os.makedirs(os.path.dirname(os.path.abspath(target)), exist_ok=True)
        img_list[0].save(tmp, save_all=True, append_images=img_list[1:], duration=duration,
                         loop=0, **kwargs)
        replace_with_retry(tmp, target)
        written[os.path.splitext(target)[1].lstrip('.')] = (target, os.path.getsize(target))

    base = os.path.splitext(out_path)[0]
    save(frames, base + '.webp', quality=72, method=4)
    save(frames, base + '.apng')
    if out_path.lower().endswith('.gif'):
        save([f.convert('P', palette=Image.ADAPTIVE, colors=192) for f in frames], out_path)
    return dict(tool='Pillow', path=out_path, width=width, fps=fps, frames=len(frames),
                duration=len(frames) / float(fps), written=written)


