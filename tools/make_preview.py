def resolve_scrub(explicit):
    """Names to blur: --scrub wins, else WFM_PREVIEW_SCRUB + tools/preview_frames/redact.txt."""
    if explicit is not None:
        return [s.strip() for s in explicit.split(',') if s.strip()]
    names = [s.strip() for s in os.environ.get('WFM_PREVIEW_SCRUB', '').split(',') if s.strip()]
    redact = os.path.join(FRAMES, 'redact.txt')
    if os.path.isfile(redact):
        with open(redact, encoding='utf-8') as f:
            names += [ln.strip() for ln in f if ln.strip() and not ln.lstrip().startswith('#')]
    seen, out = set(), []
    for n in names:
        if n.lower() not in seen:
            seen.add(n.lower())
            out.append(n)
    return out


