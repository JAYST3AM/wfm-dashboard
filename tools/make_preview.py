def main(argv=None):
    ap = argparse.ArgumentParser(description='Capture the README preview GIF + page screenshots '
                                             'from the running local dashboard.',
                                 formatter_class=argparse.ArgumentDefaultsHelpFormatter)
    ap.add_argument('--url', default=DEFAULT_URL, help='dashboard base URL (must already be running)')
    ap.add_argument('--node', default=None, help='path to node.exe')
    ap.add_argument('--chrome', default=None, help='path to chrome.exe')
    ap.add_argument('--puppeteer-core', default=None, help='path to a puppeteer-core install')
    ap.add_argument('--cadence', type=int, default=700, help='milliseconds between tour frames')
    ap.add_argument('--width', type=int, default=960, help='output animation width in px')
    ap.add_argument('--fps', type=int, default=8, help='output animation frame rate')
    ap.add_argument('--max-mb', type=float, default=4.0, help='size budget for assets/preview.gif')
    ap.add_argument('--theme', type=int, default=14, help='palette index used for the mid-tour switch (14 = Frost Light)')
    ap.add_argument('--scrub', default=None,
                    help='comma-separated names to blur in every capture; default reads '
                         'WFM_PREVIEW_SCRUB + tools/preview_frames/redact.txt (empty = no redaction)')
    ap.add_argument('--skip-posters', action='store_true', help='do not write assets/shot_*.png')
    ap.add_argument('--from-frames', action='store_true',
                    help='skip the browser capture and assemble the frames already in tools/preview_frames/')
    ap.add_argument('--only-frames', action='store_true', help='capture frames, do not assemble')
    ap.add_argument('--assemble', choices=['auto', 'ffmpeg', 'pillow', 'none'], default='auto',
                    help='which tool assembles the animation')
    ap.add_argument('--out', default=None, help='output animation path (default assets/preview.gif)')
    ap.add_argument('--keep-frames', action='store_true', default=True,
                    help='keep tools/preview_frames/ after a successful run (default: keep)')
    ap.add_argument('--view', type=str, default=None, help=argparse.SUPPRESS)
    ap.add_argument('--selftest', action='store_true', help='run offline checks and exit')
    args = ap.parse_args(argv)

    if args.selftest:
        return selftest()

    scrub = resolve_scrub(args.scrub)

    # -- preflight ----------------------------------------------------------------------
    if args.from_frames:
        node = chrome = pptr = None
        frames = sorted(glob.glob(os.path.join(FRAMES, 'frame_*.png')))
        if not frames:
            die('--from-frames: no frames in %s - run a capture first' % FRAMES)
    else:
        node = which_node(args.node)
        chrome = which_chrome(args.chrome)
        pptr = which_puppeteer(args.puppeteer_core)
        missing = []
        if not node:
            missing.append('node  (install Node.js, or pass --node / set WFM_NODE)')
        if not chrome:
            missing.append('Chrome/Edge  (pass --chrome / set WFM_CHROME)')
        if not pptr:
            missing.append('puppeteer-core  (npm i puppeteer-core in a scratch dir and pass '
                           '--puppeteer-core, or set WFM_PUPPETEER_CORE; default searched: '
                           + PUPPETEER_CANDIDATES[1] + ')')
        if missing:
            die('missing prerequisite(s):\n  - ' + '\n  - '.join(missing))
        if not server_ok(args.url):
            die('no dashboard at %s - start it first (`python server.py` or start.bat) and leave it running.' % args.url)

    os.makedirs(FRAMES, exist_ok=True)
    os.makedirs(ASSETS, exist_ok=True)
    if not args.from_frames:
        for old in glob.glob(os.path.join(FRAMES, 'frame_*.png')):
            os.remove(old)
    for old in glob.glob(os.path.join(FRAMES, 'preview_build.gif')) + glob.glob(os.path.join(FRAMES, 'palette_build.png')):
        try:
            os.remove(old)
        except OSError:
            pass

    say('WFM Trader preview builder')
    say('  url        : %s' % args.url)
    if not args.from_frames:
        say('  node       : %s' % node)
        say('  chrome     : %s' % chrome)
        say('  puppeteer  : %s' % pptr)
    else:
        say('  mode       : --from-frames (assembling %d captured frames)' % len(frames))
    say('  frames     : %s' % FRAMES)
    say('  cadence    : %d ms' % args.cadence)
    say('  redaction  : %s' % (', '.join(scrub) if scrub else
                               '(off - pass --scrub "Handle,Name" or write tools/preview_frames/redact.txt)'))

    if args.from_frames:
        first = png_size(frames[0]) or (0, 0)
        say('\nusing the %d existing frames in %s (%dx%d)' % (len(frames), FRAMES, first[0], first[1]))
    else:
        cfg = dict(
            url=args.url.rstrip('/'), cadence=args.cadence,
            w=1440, h=900, poster_w=1440, poster_h=1000,
            theme=args.theme, scrub=scrub,
            frames=FRAMES, assets=ASSETS, puppeteer=pptr, chrome=chrome,
            posters=(not args.skip_posters),
            holds=dict(home=7000, trader=5200, guardrails=6200, theme=3800,
                       market=4200, market_scroll=4200, collection=7000, cards=7000),
        )
        driver = build_driver(cfg, os.path.join(FRAMES, 'driver.cjs'))

        t0 = time.time()
        say('\ncapturing (tour: home -> trader -> settings/guardrails -> theme -> market -> collection -> cards) ...')
        try:
            rc, out, err = run([node, driver], timeout=900)
        except subprocess.TimeoutExpired:
            die('the capture run timed out after 900s', 1)
        summary = None
        for line in (out or '').splitlines():
            if line.startswith('PREVIEW_JSON '):
                try:
                    summary = json.loads(line[len('PREVIEW_JSON '):])
                except ValueError:
                    summary = None
        if summary is None:
            say((err or out or '(no output)')[-2000:])
            die('the capture run produced no summary - see the output above', 1)
        frames = sorted(glob.glob(os.path.join(FRAMES, 'frame_*.png')))
        if not summary.get('ok') or not frames:
            say(json.dumps(summary, indent=1)[:1500])
            die('capture failed', 1)

        first = png_size(frames[0]) or (0, 0)
        say('  captured %d frames in %.1fs (%dx%d)' % (len(frames), time.time() - t0, first[0], first[1]))
        if summary.get('diag'):
            say('  diagnostics: %s' % json.dumps(summary['diag'])[:400])
        if summary.get('pageErrors'):
            say('  page errors: %s' % json.dumps(summary['pageErrors'])[:400])
        for p in summary.get('posters') or []:
            full = os.path.join(ASSETS, p)
            say('  poster  %-22s %7.1f KB  %s' % (p, os.path.getsize(full) / 1024.0, png_size(full)))

        if args.only_frames or args.assemble == 'none':
            say('\nframes kept in %s (assembly skipped)' % FRAMES)
            return 0

    # -- assembly -----------------------------------------------------------------------
    out_path = args.out or os.path.join(ASSETS, 'preview.gif')
    ffmpeg = have_ffmpeg() if args.assemble in ('auto', 'ffmpeg') else None
    result = None
    if args.assemble == 'ffmpeg' and not ffmpeg:
        die('--assemble ffmpeg was requested but ffmpeg is not on PATH')
    if ffmpeg:
        say('\nassembling with ffmpeg (%s) ...' % ffmpeg)
        result = assemble_gif_ffmpeg(ffmpeg, frames, out_path, args.max_mb, first, args.fps, args.width)
        if result.get('path') is None:
            say('  ' + str(result.get('error')))
            result = None
    if result is None and (args.assemble in ('auto', 'pillow')) and have_pillow():
        say('assembling with Pillow ...')
        pillow_out = out_path if args.assemble == 'pillow' else os.path.splitext(out_path)[0] + '.webp'
        result = assemble_pillow(frames, pillow_out, args.width, args.fps, args.max_mb)
    if result is None and args.assemble == 'pillow' and not have_pillow():
        die('--assemble pillow was requested but Pillow is not importable (`pip install pillow`)')

    if result is None:
        note = write_build_note(args.fps, args.width, args.max_mb)
        say('\nno ffmpeg and no Pillow available - frames kept in %s' % FRAMES)
        say('wrote %s with the exact commands to build the GIF later.' % note)
        say('add this line to README.md once the GIF exists:')
        say('  ![Dashboard preview](assets/preview.gif)')
        return 0

    say('')
    if result.get('tool') == 'ffmpeg':
        say('preview   : %s' % result['path'])
        say('            %.2f MB, %d frames, %d px wide @ %d fps (%d colours), %.1fs loop'
            % (result['size'] / 1048576.0, result['frames'], result['width'], result['fps'],
               result['colors'], result['duration']))
        say('            %s' % result['note'])
        if result.get('publish') != 'replaced':
            say('            note: the destination was held open by another process, so the file '
                'was overwritten in place (%s)' % result.get('publish'))
    else:
        for ext, (path, size) in sorted(result['written'].items()):
            say('preview   : %s  (%.2f MB)' % (path, size / 1048576.0))
        say('            %d frames, %d px wide @ %d fps, %.1fs loop'
            % (result['frames'], result['width'], result['fps'], result['duration']))
    say('\ndone. README embed: ![Dashboard preview](%s)'
        % os.path.relpath(result['path'], ROOT).replace('\\', '/'))
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        sys.exit(130)
