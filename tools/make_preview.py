def png_size(path):
    try:
        with open(path, 'rb') as f:
            head = f.read(33)
        if head[:8] != b'\x89PNG\r\n\x1a\n':
            return None
        w, h = struct.unpack('>II', head[16:24])
        return (w, h)
    except OSError:
        return None


def make_tiny_png():
    """A real 1x1 PNG, built with stdlib zlib - used by --selftest."""
    def chunk(tag, data):
        return struct.pack('>I', len(data)) + tag + data + struct.pack('>I', zlib.crc32(tag + data) & 0xFFFFFFFF)
    ihdr = struct.pack('>IIBBBBB', 1, 1, 8, 2, 0, 0, 0)
    idat = zlib.compress(b'\x00\x00\x00\x00')
    return b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', ihdr) + chunk(b'IDAT', idat) + chunk(b'IEND', b'')


def tiers(width, fps, colors=256):
    """Quality ladder: keep the GIF under the size budget by stepping quality down."""
    out = [(width, fps, colors)]
    for c in (192, 128):
        out.append((width, fps, c))
    for f2 in (max(5, fps - 2), max(5, fps - 3)):
        out.append((width, f2, 192))
        out.append((width, f2, 128))
    out.append((max(560, int(width * 0.83)), max(5, fps - 2), 160))
    out.append((max(560, int(width * 0.70)), max(5, fps - 2), 128))
    seen, uniq = set(), []
    for t in out:
        if t not in seen:
            seen.add(t)
            uniq.append(t)
    return uniq


def run(cmd, timeout=900):
    p = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
    return p.returncode, (p.stdout or ''), (p.stderr or '')


def replace_with_retry(src, dst, tries=6, delay=0.6):
    """Put src at dst. Prefer an atomic os.replace(); on Windows a viewer, sync client or AV can
    hold dst open in a mode that blocks the swap without blocking normal writes, so retry first
    and then fall back to overwriting the file in place. Returns how it landed."""
    last = None
    for _ in range(tries):
        try:
            os.replace(src, dst)
            return 'replaced'
        except PermissionError as e:  # someone else has dst open - wait and retry
            last = e
            time.sleep(delay)
    try:
        shutil.copyfile(src, dst)
        return 'copied-in-place'
    except OSError as e:
        raise PermissionError('%s is locked by another process (%s / %s) - close whatever has it '
                              'open and re-run, or pass --out to write somewhere else'
                              % (dst, last, e))


